"""Export a generated netlist as a complete ngspice input deck.

The netlist text is passed through unchanged; strict parsing (with
`simulate`) already guarantees everything else ngspice needs, and the raw
text keeps the .model, .param, .subckt and K lines the parser does not draw.
Only the deck frame is added:

  - a title line: ngspice always reads line 1 as the title, so an element
    written there would silently disappear;
  - the solver options: gmin and source stepping are turned off, so a
    circuit is only accepted when plain Newton iteration solves it (a node
    rescued by gmin stepping is effectively tied to ground through an
    artificial conductance, i.e. the circuit is not electrically valid);
  - the analysis, then `.end`.

The netlist's own `.end` lines are dropped: ngspice stops reading at the
first `.end`, which would hide the analysis appended after it, and lines
the netlist wrote after its `.end` (which the parser does read) would not
reach ngspice either.
"""

DEFAULT_TITLE = "* netlist generated by circuit_data_gen"
# convergence aids off: only circuits plain Newton iteration solves pass
SOLVER_OPTIONS = ".options gminsteps=0 srcsteps=0"


def to_ngspice_netlist(netlist_text: str, analysis: str = ".op", title: str = DEFAULT_TITLE) -> str:
    """Wrap a (strictly parsed) netlist into an ngspice deck: title line,
    the netlist's lines without `.end`, SOLVER_OPTIONS, `analysis`, `.end`.

    `title` must be a single line; it is the deck's first line whatever it
    says (a comment is the conventional choice).
    """
    if "\n" in title:
        raise ValueError("the title must be a single line")
    body = [
        line.rstrip() for line in netlist_text.splitlines() if (line.split() or [""])[0].lower() != ".end"
    ]
    # trim blank lines around the body (inner blank lines are harmless)
    while body and not body[0]:
        body.pop(0)
    while body and not body[-1]:
        body.pop()
    return "\n".join([title, *body, SOLVER_OPTIONS, analysis, ".end"]) + "\n"
