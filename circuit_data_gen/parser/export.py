"""Export a generated netlist as a complete ngspice input deck.

The netlist text is passed through unchanged; the raw text keeps the
.model, .param, .subckt and K lines the parser does not draw. Only the deck
frame is added:

  - a title line: ngspice always reads line 1 as the title, so an element
    written there would silently disappear;
  - optionally an analysis (or a .control block), then `.end`.

The netlist's own `.end` lines are dropped: ngspice stops reading at the
first `.end`, which would hide anything appended after it, and lines the
netlist wrote after its `.end` (which the parser does read) would not reach
ngspice either.
"""

DEFAULT_TITLE = "* netlist generated by circuit_data_gen"


def to_ngspice_netlist(netlist_text: str, title: str = DEFAULT_TITLE, analysis: str | None = None) -> str:
    """Wrap a netlist into an ngspice deck: title line, the netlist's lines
    without `.end`, `analysis` (when given), `.end`.

    `title` must be a single line; it is the deck's first line whatever it
    says (a comment is the conventional choice).
    """
    if "\n" in title:
        raise ValueError("the title must be a single line")
    body = [
        line.rstrip() for line in netlist_text.splitlines() if (line.split() or [""])[0].lower() != ".end"
    ]
    # trim blank lines around the body (inner blank lines are harmless)
    while body and not body[0]:
        body.pop(0)
    while body and not body[-1]:
        body.pop()

    tail = [analysis] if analysis is not None else []
    return "\n".join([title, *body, *tail, ".end"]) + "\n"
